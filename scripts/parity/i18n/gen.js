#!/usr/bin/env node
// The widget's own words for the mobile SDKs, from the widget's i18n files.
//
//   node gen.js          writes strings.json and the RN data files
//   node gen.js --check  exits 1 when they are out of date
//
// Reads conferbot-widget/src/ts/i18n/{en,nl,fr,de,es}.ts (the web's tables,
// I18nKey = keyof typeof en) and ts/chat/games/content.ts (the quiz and word
// scramble lists per language), plus sdk-strings.json beside this script:
// the words only the SDKs draw (an app's own screens, a phone's permissions),
// written here in all five languages so Android, iOS and Flutter get the
// same ones. A key in sdk-strings.json that the web also has is an error.
//
// Writes:
//   strings.json                        { languages, names, strings: { en: {...}, ... },
//                                         sdkKeys, games: { trivia, words } } for the other SDKs
//   src/core/i18n/<lang>.data.ts        one per language (web keys, then SDK keys)
//   src/core/i18n/games.data.ts         the quiz and scramble lists
const DEV = process.env.CONFERBOT_DEV || require('path').resolve(__dirname, '../../../../..');
const fs = require('fs');
const path = require('path');

const W = `${DEV}/conferbot-widget/src/ts`;
const RN = path.resolve(__dirname, '../../..');
const LANGS = ['en', 'nl', 'fr', 'de', 'es'];
const NAMES = { en: 'English', nl: 'Nederlands', fr: 'Français', de: 'Deutsch', es: 'Español' };
const check = process.argv.includes('--check');

// An object or array literal from a TS file, evaluated as JS (the files are
// plain literals: strings, comments, no code).
const literal = (src, startRe, file) => {
  const m = startRe.exec(src);
  if (!m) throw new Error(`${file}: ${startRe} not found`);
  const open = src.indexOf(m[0]) + m[0].length - 1;
  const close = src[open] === '{' ? '}' : ']';
  // The literal ends at the first line that is only the closing bracket.
  const end = src.indexOf(`\n${close}`, open);
  if (end < 0) throw new Error(`${file}: end of ${startRe} not found`);
  // eslint-disable-next-line no-new-func
  return new Function(`return (${src.slice(open, end + 2)});`)();
};

const read = (f) => fs.readFileSync(f, 'utf8');

const web = {};
for (const lang of LANGS) {
  const file = `${W}/i18n/${lang}.ts`;
  web[lang] = literal(read(file), new RegExp(`export const ${lang}\\b[^=]*= \\{`), file);
}
const webKeys = Object.keys(web.en);

// sdk-strings.json, plus any sdk-strings.<part>.json (merged in name order).
const sdk = {};
for (const f of fs.readdirSync(__dirname).filter((n) => /^sdk-strings(\.[\w-]+)?\.json$/.test(n)).sort()) {
  const part = JSON.parse(read(path.join(__dirname, f)));
  for (const k of Object.keys(part)) {
    if (k in sdk) throw new Error(`${f}: "${k}" is defined twice`);
    sdk[k] = part[k];
  }
}
const sdkKeys = Object.keys(sdk).filter((k) => !k.startsWith('//'));
const problems = [];
for (const k of sdkKeys) {
  if (webKeys.includes(k)) problems.push(`sdk-strings.json: "${k}" is a web key`);
  for (const lang of LANGS) if (typeof sdk[k][lang] !== 'string' || !sdk[k][lang]) problems.push(`sdk-strings.json: "${k}" has no ${lang}`);
}
for (const lang of LANGS.slice(1)) {
  for (const k of Object.keys(web[lang])) if (!webKeys.includes(k)) problems.push(`${lang}.ts: "${k}" is not an en key`);
}
if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}

const strings = {};
for (const lang of LANGS) {
  strings[lang] = {};
  for (const k of webKeys) if (typeof web[lang][k] === 'string') strings[lang][k] = web[lang][k];
  for (const k of sdkKeys) strings[lang][k] = sdk[k][lang];
}

// The games' per-language lists (web ts/chat/games/content.ts).
const contentFile = `${W}/chat/games/content.ts`;
const content = read(contentFile);
const list = (name) => literal(content, new RegExp(`const ${name}\\b[^=]*= \\[`), contentFile);
const SUFFIX = { en: '', nl: '_NL', fr: '_FR', de: '_DE', es: '_ES' };
const games = { trivia: {}, words: {} };
for (const lang of LANGS) {
  games.trivia[lang] = list(`TRIVIA${SUFFIX[lang]}`);
  games.words[lang] = list(`WORDS${SUFFIX[lang]}`);
}

const out = new Map();
out.set(path.join(__dirname, 'strings.json'), JSON.stringify({ languages: LANGS, names: NAMES, strings, sdkKeys, games }, null, 1) + '\n');

const q = (s) => JSON.stringify(s);
const SRC = 'conferbot-widget/src/ts/i18n';
for (const lang of LANGS) {
  const lines = [];
  lines.push('/**');
  lines.push(` * ${NAMES[lang]}: the widget's own words. Generated by scripts/parity/i18n/gen.js`);
  lines.push(` * from ${SRC}/${lang}.ts (the web's keys, in its order) and`);
  lines.push(' * scripts/parity/i18n/sdk-strings.json (the words only the SDKs draw).');
  lines.push(' * Do not edit; change the source and run `node gen.js`.');
  lines.push(' */');
  if (lang === 'en') {
    lines.push('export const en = {');
  } else {
    lines.push("import type { I18nKey } from './en.data';");
    lines.push('');
    lines.push(`export const ${lang}: Partial<Record<I18nKey, string>> = {`);
  }
  for (const k of webKeys) if (k in strings[lang]) lines.push(`  ${q(k)}: ${q(strings[lang][k])},`);
  lines.push('  // SDK only (sdk-strings.json)');
  for (const k of sdkKeys) lines.push(`  ${q(k)}: ${q(strings[lang][k])},`);
  lines.push(lang === 'en' ? '} as const;' : '};');
  if (lang === 'en') {
    lines.push('');
    lines.push('export type I18nKey = keyof typeof en;');
  }
  out.set(path.join(RN, `src/core/i18n/${lang}.data.ts`), lines.join('\n') + '\n');
}

const g = [];
g.push('/**');
g.push(" * The waiting games' quiz and word scramble per language. Generated by");
g.push(' * scripts/parity/i18n/gen.js from conferbot-widget/src/ts/chat/games/content.ts');
g.push(' * (TRIVIA*, WORDS*). Do not edit.');
g.push(' */');
g.push("import type { WidgetLanguage } from '../i18n';");
g.push('');
g.push('export interface Trivia { q: string; a: string; wrong: string[] }');
g.push('export interface Word { w: string; hint: string }');
g.push('');
g.push(`export const TRIVIA_BY_LANG: Record<WidgetLanguage, readonly Trivia[]> = ${JSON.stringify(games.trivia, null, 2)};`);
g.push('');
g.push(`export const WORDS_BY_LANG: Record<WidgetLanguage, readonly Word[]> = ${JSON.stringify(games.words, null, 2)};`);
out.set(path.join(RN, 'src/core/i18n/games.data.ts'), g.join('\n') + '\n');

let stale = 0;
for (const [file, text] of out) {
  const now = fs.existsSync(file) ? read(file) : '';
  if (now === text) continue;
  stale++;
  if (check) console.error(`out of date: ${path.relative(RN, file)}`);
  else fs.writeFileSync(file, text);
}
const counts = LANGS.map((l) => `${l} ${Object.keys(strings[l]).length}`).join(', ');
console.log(`${webKeys.length} web keys + ${sdkKeys.length} SDK keys (${counts}); ${check ? (stale ? `${stale} stale` : 'up to date') : `${stale} written`}`);
if (check && stale) process.exit(1);
